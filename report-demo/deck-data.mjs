const palette = { bg: '#FAFBFC', ink: '#142438', muted: '#526172', accent: '#007D8A', pale: '#EEF3F5' };

function text(slide, value, x, y, width, height, size = 30, options = {}) {
  const shape = slide.shapes.add({ geometry: 'textbox', name: options.name ?? 'text', position: {left:x, top:y, width, height}, fill: 'none', line: {fill:'none', width:0} });
  shape.text = value;
  shape.text.style = {typeface: options.mono ? 'Menlo' : 'Arial', fontSize:size, color:options.color ?? palette.ink, bold:options.bold ?? false, wrap:'square', insets:0, verticalAlignment:'top', autoFit:'none', ...options.style};
  return shape;
}

function makeTable(slide, values) {
  const table = slide.tables.add({ rows:values.length, columns:3, left:72, top:180, width:1136, height:340, columnWidths:[245,480,411], values });
  table.borders.assign({fill:'#D7E0E5', width:1, style:'solid'});
  table.styleOptions = {headerRow:true, bandedRows:false};
  for (let r=0;r<values.length;r++) for (let c=0;c<3;c++) {
    const cell = table.getCell(r,c);
    cell.fill = r===0 ? palette.ink : palette.bg;
    cell.text.style = {typeface:'Arial',fontSize:r===0?25:26,bold:r===0,color:r===0?'#FFFFFF':palette.ink,insets:12,verticalAlignment:'middle',wrap:'square'};
  }
}

// Run for ranges [0,1], [1,5], [5,10], [10,15], finishing each call.
export async function buildBatch({presentation,input}) {
  const {start=0,end=1}=input??{};
  for (let index=start;index<end;index++) {
    const d=slides[index];
    const slide = index===0 && presentation.slides.items.length===1 ? presentation.slides.getItem(0) : presentation.slides.add({width:1280,height:720});
    slide.background.fill=palette.bg;
    if (d.kind==='cover') {
      text(slide,d.title,72,160,1136,210,64,{bold:true,name:'cover-title'});
      text(slide,d.subtitle,76,415,1080,96,31,{color:palette.accent,name:'subtitle'});
      text(slide,d.footer,76,620,1080,36,22,{color:palette.muted,name:'course'});
    } else {
      text(slide,d.title,72,65,1136,95,44,{bold:true,name:'title'});
      if (d.kind==='table') makeTable(slide,d.values);
      else if (d.kind==='code') text(slide,d.code,80,180,1120,420,index===4?24:28,{mono:true,name:'code'});
      else if (d.kind==='comparison') {
        d.columns.forEach((col,i)=>{
          const x=72+i*590;
          text(slide,col.title,x,183,546,70,29,{bold:true,color:i===0?palette.muted:palette.accent,name:'comparison-title'});
          text(slide,col.text,x,285,546,270,26,{mono:false,name:'comparison-body'});
        });
      } else {
        let top=185;
        if(d.lead) {text(slide,d.lead,72,180,1136,80,34,{color:palette.accent,name:'lead'});top=292;}
        const step=d.lines.length===5?76:78;
        d.lines.forEach((line,i)=>text(slide,line,72,top+i*step,1136,66,30,{name:'body'}));
      }
      if(d.bottom) text(slide,d.bottom,72,610,1070,60,23,{color:palette.muted,name:'bottom'});
      text(slide,String(index+1).padStart(2,'0'),1150,663,60,28,19,{color:palette.muted,name:'slide-number'});
    }
    slide.speakerNotes.text=d.notes+'\n\nИсточники (проверены 28.10.2026):\n'+(d.sources.length?d.sources.join('\n'):'Учебный пример и сценарий автора.');
  }
  return {added:[start,end],total:presentation.slides.items.length};
}
